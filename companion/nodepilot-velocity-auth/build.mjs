// Run with a JDK 25+ on PATH. Only NodePilot's own classes/resources are bundled.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('./', import.meta.url));
const build = path.join(root, '.build');
await mkdir(build, { recursive: true });
const dependencies = [
  ['velocity.jar', 'https://fill-data.papermc.io/v1/objects/0844bcabdcdb4f5b875906fd4c3365bc1bb76918e42bc595ed88ad195258dd75/velocity-4.3.1-45.jar', '0844bcabdcdb4f5b875906fd4c3365bc1bb76918e42bc595ed88ad195258dd75'],
  ['EaglerXServer.jar', 'https://github.com/lax1dude/eaglerxserver/releases/download/v1.1.1/EaglerXServer.jar', '468cb07eb7ca466b21b439be75156d3d01579327f4c6dae5b67d471137a64208'],
];
for (const [fileName, url, sha256] of dependencies) {
  const target = path.join(build, fileName);
  let buffer;
  try { buffer = await readFile(target); } catch {}
  if (!buffer || createHash('sha256').update(buffer).digest('hex') !== sha256) {
    const response = await fetch(url, { signal: AbortSignal.timeout(120_000) });
    if (!response.ok) throw new Error('Dependency download failed with HTTP ' + response.status);
    buffer = Buffer.from(await response.arrayBuffer());
    if (buffer.length > 64 * 1024 * 1024 || createHash('sha256').update(buffer).digest('hex') !== sha256) {
      throw new Error('Dependency checksum mismatch.');
    }
    await writeFile(target, buffer);
  }
}
const classes = await mkdtemp(path.join(build, 'classes-'));
const artifact = path.join(build, 'nodepilot-browser-auth.jar');
try {
  execFileSync('javac', ['--release', '17', '-proc:none', '-encoding', 'UTF-8',
    '-cp', dependencies.map(([name]) => path.join(build, name)).join(path.delimiter),
    '-d', classes, path.join(root, 'src/main/java/dev/nodepilot/browser/BrowserAuth.java')], { stdio: 'inherit' });
  await writeFile(path.join(classes, 'velocity-plugin.json'), await readFile(path.join(root, 'src/main/resources/velocity-plugin.json')));
  execFileSync('jar', ['--create', '--file', artifact, '--date=2025-01-01T00:00:00Z', '-C', classes, '.'], { stdio: 'inherit' });
} finally {
  await rm(classes, { recursive: true, force: true });
}
const bytes = await readFile(artifact);
const digest = createHash('sha256').update(bytes).digest('hex');
const source = '// Generated by companion/nodepilot-velocity-auth/build.mjs. Contains only NodePilot classes.\n'
  + "export const BROWSER_AUTH_JAR_SHA256 = '" + digest + "';\n"
  + "export const BROWSER_AUTH_JAR_BASE64 = '" + bytes.toString('base64') + "';\n";
if (!process.argv.includes('--check')) {
  await writeFile(path.resolve(root, '../../server/services/browser-auth-artifact.ts'), source);
}
console.log('Built NodePilot browser gateway companion. SHA-256 ' + digest);
