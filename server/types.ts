export const serverStatuses = [
  'offline',
  'installing',
  'starting',
  'running',
  'stopping',
  'error',
] as const;

export type ServerStatus = (typeof serverStatuses)[number];
export type InstallState = 'installing' | 'ready' | 'failed';
export type ServerFlavor = 'vanilla' | 'paper';
/**
 * `flavor` is kept as a two-value legacy compatibility field while `software` is the
 * authoritative Minecraft server implementation. New code should use `software`.
 */
export type ServerSoftware =
  | 'vanilla'
  | 'paper'
  | 'spigot'
  | 'purpur'
  | 'fabric'
  | 'forge'
  | 'neoforge'
  | 'quilt'
  | 'bedrock'
  | 'unknown';

export type ProvisionableServerSoftware = Exclude<ServerSoftware, 'unknown'>;

/**
 * A launch description created exclusively by a trusted software installer or importer.
 * All paths are relative to the managed server directory. The runtime must reject absolute
 * paths and traversal before using this data, even though repository writes validate it too.
 */
export type ServerStartupConfig =
  | {
      mode: 'jar';
      jarPath: string;
      gameArguments: string[];
    }
  | {
      mode: 'arg-files';
      windowsArgFile: string;
      linuxArgFile: string;
      /** Optional JVM argument files generated by an installer, for example user_jvm_args.txt. */
      jvmArgFiles: string[];
      gameArguments: string[];
    }
  | {
      mode: 'executable';
      executablePath: string;
      gameArguments: string[];
    };

export const defaultServerStartupConfig: ServerStartupConfig = {
  mode: 'jar',
  jarPath: 'server.jar',
  gameArguments: ['nogui'],
};

export type AutoStartMode = 'always' | 'disabled';

export interface ServerRecord {
  id: string;
  /** The local runner today; retained so remote agents can be introduced without remapping records. */
  machineId: string;
  name: string;
  directory: string;
  game: 'minecraft-java' | 'minecraft-bedrock';
  flavor: ServerFlavor;
  software: ServerSoftware;
  version: string;
  /** Fabric/Quilt loader or Forge/NeoForge build selected by the trusted metadata service. */
  loaderVersion: string | null;
  startupConfig: ServerStartupConfig;
  requiredJavaMajor: number | null;
  port: number;
  memoryMb: number;
  eulaAccepted: boolean;
  status: ServerStatus;
  installState: InstallState;
  javaPath: string | null;
  autoStart: AutoStartMode;
  lastError: string | null;
  createdAt: string;
  updatedAt: string;
  lastStartedAt: string | null;
  lastStoppedAt: string | null;
}

