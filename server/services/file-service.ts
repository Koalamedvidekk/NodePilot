import { randomUUID } from 'node:crypto';
import { cp, mkdir, readdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { AppError } from '../lib/errors.js';
import { isInside, isRegularFile, resolveInside, resolveManagedServerRoot } from '../lib/paths.js';
import type { FileEntry, ServerRecord } from '../types.js';

const MAX_TEXT_BYTES = 1_000_000;
const MAX_LIST_ENTRIES = 500;
const PROTECTED_FILES = new Set(['server.jar', 'eula.txt']);

function toRelative(root: string, target: string): string {
  return path.relative(root, target).split(path.sep).join('/');
}

function assertText(value: string): void {
  if (Buffer.byteLength(value, 'utf8') > MAX_TEXT_BYTES || value.includes('\0')) {
    throw new AppError(413, 'file_too_large_or_binary', 'Only UTF-8 text files up to 1 MB can be edited.');
  }
}

function normalizedBasename(relativePath: string): string {
  return path.basename(relativePath).toLocaleLowerCase();
}

function isProtected(relativePath: string): boolean {
  return PROTECTED_FILES.has(normalizedBasename(relativePath));
}

function isValidEntryName(name: string): boolean {
  if (typeof name !== 'string') return false;
  const trimmed = name.trim();
  if (!trimmed || trimmed !== name) return false;
  if (name.includes('/') || name.includes('\\') || name.includes('\0') || name === '.' || name === '..') return false;
  if (/[<>:"/\\|?*\x00-\x1f]/.test(name)) return false;
  return name.length <= 255;
}

async function pathExists(filePath: string): Promise<boolean> {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

async function atomicWrite(filePath: string, content: string, mode?: number): Promise<void> {
  // The random, exclusively-created temporary file avoids following a plugin-created symlink.
  const temporary = `${filePath}.nodepilot-${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, content, { encoding: 'utf8', flag: 'wx', mode });
    await rename(temporary, filePath);
  } finally {
    await rm(temporary, { force: true }).catch(() => undefined);
  }
}

export class FileService {
  constructor(private readonly serversDirectory: string) {}

  private async serverRoot(server: ServerRecord): Promise<string> {
    // `directory` is generated by NodePilot (UUID suffix) and never accepts a client path.
    return resolveManagedServerRoot(this.serversDirectory, server.directory);
  }

  async list(server: ServerRecord, requestedPath = ''): Promise<FileEntry[]> {
    const root = await this.serverRoot(server);
    const directory = await resolveInside(root, requestedPath);
    const info = await stat(directory);
    if (!info.isDirectory()) throw new AppError(400, 'not_a_directory', 'Select a directory to list its files.');
    const entries = await readdir(directory, { withFileTypes: true });
    if (entries.length > MAX_LIST_ENTRIES) {
      throw new AppError(413, 'directory_too_large', `This directory has more than ${MAX_LIST_ENTRIES} entries.`);
    }
    const values = await Promise.all(entries
      .filter((entry) => !entry.isSymbolicLink())
      .map(async (entry): Promise<FileEntry> => {
        const absolute = path.join(directory, entry.name);
        const entryStat = await stat(absolute);
        return {
          name: entry.name,
          path: toRelative(root, absolute),
          type: entryStat.isDirectory() ? 'directory' : 'file',
          size: entryStat.size,
          modifiedAt: entryStat.mtime.toISOString(),
        };
      }));
    return values.sort((left, right) => Number(right.type === 'directory') - Number(left.type === 'directory') || left.name.localeCompare(right.name));
  }

  async readText(server: ServerRecord, requestedPath: string): Promise<{ path: string; content: string; encoding: 'utf8' }> {
    const root = await this.serverRoot(server);
    const filePath = await resolveInside(root, requestedPath);
    if (!(await isRegularFile(filePath))) throw new AppError(400, 'not_a_file', 'Select a regular file to read.');
    const fileStat = await stat(filePath);
    if (fileStat.size > MAX_TEXT_BYTES) throw new AppError(413, 'file_too_large', 'Only text files up to 1 MB can be opened in NodePilot.');
    const content = await readFile(filePath, 'utf8');
    assertText(content);
    return { path: toRelative(root, filePath), content, encoding: 'utf8' };
  }

  async writeText(server: ServerRecord, requestedPath: string, content: string): Promise<{ path: string }> {
    if (typeof content !== 'string') throw new AppError(400, 'invalid_content', 'File content must be text.');
    assertText(content);
    const root = await this.serverRoot(server);
    const filePath = await resolveInside(root, requestedPath);
    const relative = toRelative(root, filePath);
    if (PROTECTED_FILES.has(normalizedBasename(relative))) {
      throw new AppError(403, 'protected_file', 'NodePilot protects this generated server file.');
    }
    if (!(await isRegularFile(filePath))) throw new AppError(400, 'not_a_file', 'Only existing regular text files can be edited.');
    const previous = await stat(filePath);
    if (previous.size > MAX_TEXT_BYTES) throw new AppError(413, 'file_too_large', 'Only text files up to 1 MB can be edited.');
    const existing = await readFile(filePath, 'utf8');
    assertText(existing);
    await atomicWrite(filePath, content, previous.mode);
    return { path: relative };
  }

  async delete(server: ServerRecord, requestedPath: string): Promise<void> {
    const root = await this.serverRoot(server);
    if (!requestedPath || requestedPath === '.' || requestedPath === '/') {
      throw new AppError(400, 'cannot_delete_root', 'Cannot delete the server root directory.');
    }
    const targetPath = await resolveInside(root, requestedPath, true);
    if (targetPath === root) {
      throw new AppError(400, 'cannot_delete_root', 'Cannot delete the server root directory.');
    }
    const relative = toRelative(root, targetPath);
    if (isProtected(relative)) {
      throw new AppError(403, 'protected_file', 'NodePilot protects this server file from deletion.');
    }
    await rm(targetPath, { recursive: true, force: true });
  }

  async rename(server: ServerRecord, requestedPath: string, newName: string): Promise<{ path: string }> {
    if (!isValidEntryName(newName)) {
      throw new AppError(400, 'invalid_name', 'The target name contains invalid characters or is empty.');
    }
    if (PROTECTED_FILES.has(newName.toLowerCase())) {
      throw new AppError(403, 'protected_file', 'Cannot rename an item to a protected server file name.');
    }
    const root = await this.serverRoot(server);
    if (!requestedPath || requestedPath === '.' || requestedPath === '/') {
      throw new AppError(400, 'cannot_rename_root', 'Cannot rename the server root directory.');
    }
    const sourcePath = await resolveInside(root, requestedPath, true);
    if (sourcePath === root) {
      throw new AppError(400, 'cannot_rename_root', 'Cannot rename the server root directory.');
    }
    const sourceRelative = toRelative(root, sourcePath);
    if (isProtected(sourceRelative)) {
      throw new AppError(403, 'protected_file', 'NodePilot protects this server file from being renamed.');
    }
    const parentDirectory = path.dirname(sourcePath);
    const destinationPath = path.join(parentDirectory, newName);
    if (await pathExists(destinationPath)) {
      throw new AppError(409, 'target_already_exists', `An item named "${newName}" already exists in this folder.`);
    }
    await rename(sourcePath, destinationPath);
    return { path: toRelative(root, destinationPath) };
  }

  async createFile(server: ServerRecord, parentPath: string, fileName: string, content = ''): Promise<{ path: string }> {
    if (!isValidEntryName(fileName)) {
      throw new AppError(400, 'invalid_name', 'The file name contains invalid characters or is empty.');
    }
    if (PROTECTED_FILES.has(fileName.toLowerCase())) {
      throw new AppError(403, 'protected_file', 'Cannot create a protected server file.');
    }
    assertText(content);
    const root = await this.serverRoot(server);
    const parentDir = await resolveInside(root, parentPath, true);
    const parentStat = await stat(parentDir);
    if (!parentStat.isDirectory()) {
      throw new AppError(400, 'not_a_directory', 'Parent path is not a directory.');
    }
    const destinationPath = path.join(parentDir, fileName);
    if (await pathExists(destinationPath)) {
      throw new AppError(409, 'file_already_exists', `An item named "${fileName}" already exists in this folder.`);
    }
    await writeFile(destinationPath, content, { encoding: 'utf8', flag: 'wx' });
    return { path: toRelative(root, destinationPath) };
  }

  async createFolder(server: ServerRecord, parentPath: string, folderName: string): Promise<{ path: string }> {
    if (!isValidEntryName(folderName)) {
      throw new AppError(400, 'invalid_name', 'The folder name contains invalid characters or is empty.');
    }
    const root = await this.serverRoot(server);
    const parentDir = await resolveInside(root, parentPath, true);
    const parentStat = await stat(parentDir);
    if (!parentStat.isDirectory()) {
      throw new AppError(400, 'not_a_directory', 'Parent path is not a directory.');
    }
    const destinationPath = path.join(parentDir, folderName);
    if (await pathExists(destinationPath)) {
      throw new AppError(409, 'folder_already_exists', `An item named "${folderName}" already exists in this folder.`);
    }
    await mkdir(destinationPath, { recursive: false });
    return { path: toRelative(root, destinationPath) };
  }

  async copy(server: ServerRecord, sourcePath: string, destinationDir: string): Promise<{ path: string }> {
    const root = await this.serverRoot(server);
    if (!sourcePath || sourcePath === '.' || sourcePath === '/') {
      throw new AppError(400, 'cannot_copy_root', 'Cannot copy the server root directory.');
    }
    const source = await resolveInside(root, sourcePath, true);
    if (source === root) {
      throw new AppError(400, 'cannot_copy_root', 'Cannot copy the server root directory.');
    }
    const destDir = await resolveInside(root, destinationDir, true);
    const destStat = await stat(destDir);
    if (!destStat.isDirectory()) {
      throw new AppError(400, 'not_a_directory', 'Destination path is not a directory.');
    }
    const sourceStat = await stat(source);
    if (sourceStat.isDirectory() && (source === destDir || isInside(source, destDir))) {
      throw new AppError(400, 'cannot_copy_into_self', 'Cannot copy a directory into itself or one of its subdirectories.');
    }
    let targetName = path.basename(source);
    let destination = path.join(destDir, targetName);
    if (await pathExists(destination)) {
      const ext = sourceStat.isDirectory() ? '' : path.extname(targetName);
      const base = sourceStat.isDirectory() ? targetName : path.basename(targetName, ext);
      let counter = 1;
      let candidateName = `${base}-copy${ext}`;
      while (await pathExists(path.join(destDir, candidateName))) {
        counter += 1;
        candidateName = `${base}-copy-${counter}${ext}`;
      }
      targetName = candidateName;
      destination = path.join(destDir, targetName);
    }
    if (PROTECTED_FILES.has(targetName.toLowerCase())) {
      throw new AppError(403, 'protected_file', 'Cannot copy onto a protected server file name.');
    }
    await cp(source, destination, { recursive: true });
    return { path: toRelative(root, destination) };
  }

  async move(server: ServerRecord, sourcePath: string, destinationDir: string): Promise<{ path: string }> {
    const root = await this.serverRoot(server);
    if (!sourcePath || sourcePath === '.' || sourcePath === '/') {
      throw new AppError(400, 'cannot_move_root', 'Cannot move the server root directory.');
    }
    const source = await resolveInside(root, sourcePath, true);
    if (source === root) {
      throw new AppError(400, 'cannot_move_root', 'Cannot move the server root directory.');
    }
    const sourceRelative = toRelative(root, source);
    if (isProtected(sourceRelative)) {
      throw new AppError(403, 'protected_file', 'NodePilot protects this server file from being moved.');
    }
    const destDir = await resolveInside(root, destinationDir, true);
    const destStat = await stat(destDir);
    if (!destStat.isDirectory()) {
      throw new AppError(400, 'not_a_directory', 'Destination path is not a directory.');
    }
    const sourceStat = await stat(source);
    if (sourceStat.isDirectory() && (source === destDir || isInside(source, destDir))) {
      throw new AppError(400, 'cannot_move_into_self', 'Cannot move a directory into itself or one of its subdirectories.');
    }
    const targetName = path.basename(source);
    const destination = path.join(destDir, targetName);
    if (source === destination) {
      return { path: toRelative(root, destination) };
    }
    if (await pathExists(destination)) {
      throw new AppError(409, 'target_already_exists', `An item named "${targetName}" already exists in the destination folder.`);
    }
    if (PROTECTED_FILES.has(targetName.toLowerCase())) {
      throw new AppError(403, 'protected_file', 'Cannot move onto a protected server file name.');
    }
    await rename(source, destination);
    return { path: toRelative(root, destination) };
  }

  async getProperties(server: ServerRecord): Promise<Record<string, string>> {
    const root = await this.serverRoot(server);
    const filePath = await resolveInside(root, 'server.properties');
    if (!(await isRegularFile(filePath))) throw new AppError(400, 'not_a_file', 'server.properties is not a regular file.');
    const content = await readFile(filePath, 'utf8');
    assertText(content);
    const values: Record<string, string> = {};
    for (const rawLine of content.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line || line.startsWith('#')) continue;
      const splitAt = line.indexOf('=');
      if (splitAt < 1) continue;
      values[line.slice(0, splitAt).trim()] = line.slice(splitAt + 1);
    }
    return values;
  }

  async saveProperties(server: ServerRecord, values: Record<string, string>): Promise<Record<string, string>> {
    const pairs = Object.entries(values);
    if (pairs.length > 200) throw new AppError(400, 'too_many_properties', 'A server properties file may contain at most 200 values.');
    for (const [key, value] of pairs) {
      if (!/^[A-Za-z0-9_.-]{1,64}$/.test(key) || typeof value !== 'string' || value.length > 512 || /[\r\n\0]/.test(value)) {
        throw new AppError(400, 'invalid_property', 'Property names and values contain unsupported characters.');
      }
    }
    const root = await this.serverRoot(server);
    const filePath = await resolveInside(root, 'server.properties');
    if (!(await isRegularFile(filePath))) throw new AppError(400, 'not_a_file', 'server.properties is not a regular file.');
    const output = [
      '# Managed by NodePilot. Changes may require a server restart.',
      ...pairs.sort(([left], [right]) => left.localeCompare(right)).map(([key, value]) => `${key}=${value}`),
      '',
    ].join('\n');
    await atomicWrite(filePath, output);
    return Object.fromEntries(pairs);
  }
}
